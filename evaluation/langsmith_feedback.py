"""기존 기록을 같은 데이터셋의 새 비교 실험으로 게시한다. 원본 trace는 수정하지 않는다."""
import argparse
from datetime import datetime, timedelta
import hashlib
import json
import os
from pathlib import Path
import time
from uuid import UUID, uuid5

from .compare import compare_bundles
from .contracts import ROOT, dataset_turns, load_bundle, write_json


OWNER = "incident-evaluation-v1"


def _read_after_write(read, resource_id):
    """원격 색인 반영 지연은 조회만 재시도한다. 게시 실패를 무한 재시도하지 않는다."""
    from langsmith.utils import LangSmithNotFoundError
    for delay in (0.5, 1, 2, 4, 8):
        try:
            return read(resource_id)
        except LangSmithNotFoundError:
            time.sleep(delay)
    return read(resource_id)


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, allow_nan=False).encode()).hexdigest()


def build_publication(before, after):
    compare_bundles(before, after)
    dataset = before["dataset"]
    digest = before["manifest"]["dataset_sha256"]
    examples = [{"key": f"{case_id}/{number}", "inputs": {"case_id": case_id, "turn": number, "message": turn["message"],
                 "session_policy": "turns in same case share session; prior turn generated by evaluated variant"},
                 "outputs": turn} for (case_id, number), turn in dataset_turns(dataset).items()]
    spec = {"owner": OWNER, "dataset_name": f"incident-evaluation-{digest[:16]}", "dataset_sha256": digest,
            "examples": examples, "experiments": []}
    for phase, bundle in (("before", before), ("after", after)):
        manifest = bundle["manifest"]
        # 사용자가 판정을 바꾸면 기존 점수를 덮어쓰지 않고 다른 실험으로 남긴다.
        identity = fingerprint({"manifest": manifest, "records": bundle["records"]})
        experiment = {"name": f"incident-{phase}-{manifest['run_id']}-{identity[:12]}",
                      "metadata": {"owner": OWNER, "fingerprint": identity, "phase": phase,
                                   "source_run_id": manifest["run_id"], "dataset_sha256": digest,
                                   "profile": manifest.get("profile"), "imported_recording": True,
                                   "source_sha256": manifest.get("source_sha256") or manifest.get("source_manifest", {}).get("files_sha256", {})},
                      "rows": []}
        for record in bundle["records"]:
            if record["status"] == "not_run":
                raise ValueError("LangSmith publication requires all requests recorded; keep incomplete run locally")
            start = record.get("trace_started_at") or record.get("started_at")
            if not start:
                raise ValueError("recorded start time required for experiment latency")
            boundary = "trace" if record.get("trace_started_at") and record.get("trace_elapsed_ms") is not None else "http"
            elapsed = record.get(boundary + "_elapsed_ms")
            if elapsed is None:
                raise ValueError("recorded duration required")
            feedback = []
            for key in ("request_success", "route_correct", "target_exact", "clarification_safe", "retrieval_recall",
                        "retrieval_precision", "unnecessary_retrieval", "answer_pass", "numeric_grounding_pass"):
                score = record["scores"].get(key)
                if score is None:
                    continue
                manual = key in ("answer_pass", "numeric_grounding_pass") and record.get("review") is not None
                feedback.append({"key": key, "score": score,
                                 "method": "manual_record_review" if manual else "deterministic_rule_v1",
                                 "comment": (record["review"].get("reviewer", "") + ": " + record["review"].get("notes", "")) if manual
                                 else "관측 이벤트 기준 자동 점수. 자연어 사실 정확도 판정과 별도."})
            for kind in ("http", "trace"):
                value = record.get(kind + "_elapsed_ms")
                if value is not None:
                    feedback.append({"key": kind + "_latency_ms", "score": value,
                                     "method": "measurement", "comment": f"원본 {kind} 측정 경계; ms"})
            for provider in ("openai", "ollama"):
                calls = [u for u in record.get("model_usage") or [] if u["provider"] == provider]
                if record.get("model_usage") is not None and all(c.get("usage") is not None for c in calls):
                    feedback.append({"key": provider + "_tokens", "score": sum(c["usage"]["total_tokens"] for c in calls),
                                     "method": "provider_usage", "comment": "공급자 응답 토큰. 임베딩 토큰 제외."})
            estimate = record.get("langsmith_estimated_cost_usd")
            if estimate is not None:
                feedback.append({"key": "langsmith_estimated_cost_usd", "score": float(estimate),
                                 "method": "langsmith_pricing", "comment": "원본 trace의 가격표 추정 비용. 실제 청구액 미확인."})
            experiment["rows"].append({
                "key": f"{record['case_id']}/{record['turn']}/{record['repetition']}",
                "example_key": f"{record['case_id']}/{record['turn']}",
                "start_time": start, "duration_ms": elapsed,
                "error": record.get("error", "request_failed") if record["status"] != "ok" else None,
                "outputs": {"reply": (record.get("response") or {}).get("reply"),
                            "events": (record.get("response") or {}).get("events", []),
                            "evidence": (record.get("state") or {}).get("collected", []),
                            "scores": record["scores"], "manual_review": record.get("review")},
                "metadata": {"case_id": record["case_id"], "turn": record["turn"], "repetition": record["repetition"],
                             "source_run_id": record.get("source_run_id"), "source_run_url": record.get("source_run_url"),
                             "duration_basis": boundary, "imported_recording": True, "actual_billed_usd": None},
                "feedback": feedback})
        spec["experiments"].append(experiment)
    return spec


def publish(spec, client):
    from langsmith.utils import LangSmithNotFoundError
    try:
        dataset = client.read_dataset(dataset_name=spec["dataset_name"])
    except LangSmithNotFoundError:
        dataset = client.create_dataset(spec["dataset_name"], description="고정 회귀셋의 Before/After 원자료 비교; 새 모델 실행이 아닌 기록 사본",
                                        metadata={"owner": OWNER, "dataset_sha256": spec["dataset_sha256"]})
    if (dataset.metadata or {}).get("owner") != OWNER or dataset.metadata.get("dataset_sha256") != spec["dataset_sha256"]:
        raise ValueError("existing dataset ownership/content mismatch")
    examples = {}
    for item in spec["examples"]:
        example_id = uuid5(UUID(str(dataset.id)), item["key"])
        try:
            existing = client.read_example(example_id)
        except LangSmithNotFoundError:
            existing = client.create_example(example_id=example_id, dataset_id=dataset.id, inputs=item["inputs"],
                                              outputs=item["outputs"], metadata={"owner": OWNER, "case_turn": item["key"]})
        if existing.inputs != item["inputs"] or existing.outputs != item["outputs"] or str(existing.dataset_id) != str(dataset.id):
            raise ValueError("existing example mismatch")
        examples[item["key"]] = (example_id, item["inputs"])
    result = {"dataset_id": str(dataset.id), "dataset_url": getattr(dataset, "url", None),
              "experiments": [], "verified_runs": 0, "verified_feedback": 0,
              "feedback_score_decimal_places": 4}
    for experiment in spec["experiments"]:
        try:
            project = client.read_project(project_name=experiment["name"])
        except LangSmithNotFoundError:
            project = client.create_project(experiment["name"], reference_dataset_id=dataset.id,
                                            metadata=experiment["metadata"],
                                            description="원자료 사본. 원본 추적 ID는 metadata; 자동 점수와 수동 판정 분리.")
        if (project.metadata or {}).get("fingerprint") != experiment["metadata"]["fingerprint"] or str(project.reference_dataset_id) != str(dataset.id):
            raise ValueError("existing experiment mismatch")
        for row in experiment["rows"]:
            run_id = uuid5(UUID(str(project.id)), row["key"])
            example_id, inputs = examples[row["example_key"]]
            try:
                client.read_run(run_id)
            except LangSmithNotFoundError:
                start = datetime.fromisoformat(row["start_time"])
                if start.tzinfo is None:
                    raise ValueError("timezone-aware recorded timestamp required")
                client.create_run(id=run_id, name="recorded_request", inputs=inputs, run_type="chain",
                                  project_name=experiment["name"], reference_example_id=example_id,
                                  outputs=row["outputs"], start_time=start,
                                  end_time=start + timedelta(milliseconds=row["duration_ms"]),
                                  error=row["error"], extra={"metadata": row["metadata"]})
            remote = _read_after_write(client.read_run, run_id)
            if (remote.inputs != inputs or remote.outputs != row["outputs"] or remote.error != row["error"]
                    or str(remote.reference_example_id) != str(example_id)):
                raise ValueError("run read-back mismatch")
            result["verified_runs"] += 1
            for feedback in row["feedback"]:
                feedback_id = uuid5(run_id, feedback["key"])
                try:
                    client.read_feedback(feedback_id)
                except LangSmithNotFoundError:
                    client.create_feedback(run_id, feedback["key"], feedback_id=feedback_id, score=feedback["score"],
                                           session_id=project.id, comment=feedback["comment"],
                                           source_info={"method": feedback["method"], "owner": OWNER})
                checked = _read_after_write(client.read_feedback, feedback_id)
                # LangSmith SDK formats float feedback scores with round(score, 4).
                # 원 정밀도는 publication.json과 원본 trace에 보존한다.
                expected_score = round(feedback["score"], 4)
                if checked.score != expected_score or checked.key != feedback["key"] or str(checked.run_id) != str(run_id):
                    raise ValueError("feedback read-back mismatch")
                result["verified_feedback"] += 1
        result["experiments"].append({"name": experiment["name"], "id": str(project.id), "url": getattr(project, "url", None)})
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--before", required=True, type=Path)
    parser.add_argument("--after", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path, help="전송 검토용 JSON과 receipt 디렉터리")
    parser.add_argument("--publish", action="store_true", help="질문·답변·근거·점수를 LangSmith로 게시")
    args = parser.parse_args(argv)
    if any(args.output.resolve().is_relative_to(p.resolve()) for p in (args.before, args.after)):
        raise ValueError("publication output must be outside source runs")
    spec = build_publication(load_bundle(args.before), load_bundle(args.after))
    args.output.mkdir(parents=True, exist_ok=True)
    payload = args.output / "publication.json"
    if payload.exists() and json.loads(payload.read_text()) != spec:
        raise ValueError("publication directory contains a different payload")
    write_json(payload, spec)
    if not args.publish:
        print(f"전송 없음. 검토용 payload: {payload}")
        return 0
    from dotenv import dotenv_values
    from langsmith import Client
    config = {**dotenv_values(ROOT / ".env"), **os.environ}
    key = config.get("LANGSMITH_API_KEY") or config.get("LANGCHAIN_API_KEY")
    if not key:
        raise ValueError("LangSmith API key missing")
    client = Client(api_key=key, api_url=config.get("LANGSMITH_ENDPOINT") or config.get("LANGCHAIN_ENDPOINT") or "https://api.smith.langchain.com",
                    workspace_id=config.get("LANGSMITH_WORKSPACE_ID"), auto_batch_tracing=False, timeout_ms=15000)
    try:
        result = publish(spec, client)
        write_json(args.output / "receipt.json", result)
        print(json.dumps(result, ensure_ascii=False))
    finally:
        client.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
